# =============================================================================
# src/ai_news_crew/tasks.py — Task definitions for the AI News Crew
# =============================================================================
#
# WHAT IS A CREWAI TASK?
#   A Task is a concrete piece of work assigned to an agent, defining:
#     - DESCRIPTION    : Detailed work instructions (the agent's "brief")
#     - EXPECTED_OUTPUT: Exact format required in the response
#     - AGENT          : Which agent is responsible for this task
#     - CONTEXT        : (Optional) outputs from prior tasks to inject
#     - OUTPUT_FILE    : (Optional) auto-saves final output to disk
#
# TASK CHAINING via context=[]:
#   context=[research_task] automatically appends the research task's
#   output into the writer task's prompt. The writer sees all the raw
#   research before it starts writing — no manual passing of data needed.
#
# TIP: Specificity matters.
#   Tell the agent exactly what format, fields, and detail level you need.
#   Vague descriptions produce vague results.
#
# =============================================================================

from datetime import datetime

from crewai import Agent, Task


def create_research_task(researcher: Agent) -> Task:
    """Research task: find and document the top AI/LLM news of the past week."""
    today = datetime.now().strftime("%B %d, %Y")

    return Task(
        description=(
            f"Today is {today}. Search the web for the most important "
            f"AI and LLM news from the past 7 days.\n\n"
            f"Required categories:\n"
            f"  1. New model releases (GPT, Claude, Gemini, Llama, etc.)\n"
            f"  2. Significant research papers or breakthroughs\n"
            f"  3. Major product launches or feature announcements\n"
            f"  4. Industry news (acquisitions, funding, policy, safety)\n"
            f"  5. Open-source community highlights\n\n"
            f"Suggested searches: 'AI news {today[:4]} this week', "
            f"'new LLM model released', 'AI research paper', "
            f"'generative AI product launch'.\n\n"
            f"For each story record: headline, source name, URL, "
            f"publication date, 2-3 sentence summary, and category.\n"
            f"Use the scrape tool to read full articles for significant stories."
        ),
        expected_output=(
            "A structured report with 8-10 AI/LLM news stories from the past 7 days. "
            "Each entry: headline, source name, URL, date, factual summary, category. "
            "Ordered by significance. Include a 3-5 sentence overview at the top "
            "summarising the week's themes."
        ),
        agent=researcher,
    )


def create_write_task(writer: Agent, research_task: Task, output_file: str) -> Task:
    """Writing task: transform research findings into a polished Markdown report."""
    today = datetime.now().strftime("%B %d, %Y")
    date_slug = datetime.now().strftime("%Y-%m-%d")

    return Task(
        description=(
            f"Using ONLY the provided research findings, write a Markdown report "
            f"for {today}.\n\n"
            f"Required structure:\n"
            f"  # AI & LLM News Digest - {date_slug}\n"
            f"  ## Executive Summary   (3-5 sentence big picture)\n"
            f"  ## Top Stories         (3-4 most significant, each with ### heading)\n"
            f"  ## Model Releases & Updates\n"
            f"  ## Research Highlights\n"
            f"  ## Industry & Business News\n"
            f"  ## Open Source & Community\n"
            f"  ## Trends to Watch     (3-5 bullet points)\n"
            f"  ## Sources             (numbered list with links)\n\n"
            f"Rules: bold key terms/models/companies, inline source links "
            f"([Name](URL)), skip empty sections, min 800 words, "
            f"end with '*Report generated by AI News Crew on {today}*'."
        ),
        expected_output=(
            f"A complete Markdown document 'AI & LLM News Digest — {date_slug}' "
            f"with all sections, proper formatting, inline links, 800+ words. "
            f"Ready to publish. Facts from research only — no invented details."
        ),
        # Passes the researcher's output into this task's prompt automatically
        context=[research_task],
        agent=writer,
        # CrewAI writes the final answer to this file path automatically
        output_file=output_file,
    )
